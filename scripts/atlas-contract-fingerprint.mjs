import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const sourceDirectories = [
  'packages/schema/src',
  'packages/master-data/src',
  'packages/data-pipeline/src',
  'packages/calc-core/src',
  'packages/battle-execution/src',
  'packages/calculation-application/src',
];
const additionalFiles = [
  'apps/web/src/adapters/atlasSource.ts',
  'apps/web/src/adapters/atlasRepository.ts',
  'apps/web/src/adapters/atlasMasterClient.ts',
  'apps/web/src/workers/atlasMasterWorker.ts',
];
const outputPath = join(root, 'apps/web/src/adapters/atlasContractFingerprint.ts');
const excluded = /(?:\.test|\.bench|\.spec|\.d)\.tsx?$/;

async function sourceFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await sourceFiles(path)));
    else if (entry.isFile() && /\.tsx?$/.test(entry.name) && !excluded.test(entry.name))
      files.push(path);
    else if (!entry.isFile()) throw new TypeError(`contract_fingerprint:unexpected_entry:${path}`);
  }
  return files;
}

export async function computeAtlasContractFingerprint() {
  const files = [
    ...additionalFiles.map((path) => join(root, path)),
    ...(await Promise.all(sourceDirectories.map((path) => sourceFiles(join(root, path))))).flat(),
  ].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const hash = createHash('sha256').update('fgo-lab-atlas-contract-v1\0');
  for (const file of files) {
    const path = relative(root, file).replaceAll('\\', '/');
    const content = await readFile(file);
    hash.update(path).update('\0').update(String(content.byteLength)).update('\0').update(content);
  }
  return hash.digest('hex');
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const mode = process.argv[2];
  if (mode !== '--write' && mode !== '--check')
    throw new TypeError('usage: node scripts/atlas-contract-fingerprint.mjs <--write|--check>');
  const digest = await computeAtlasContractFingerprint();
  const expected = `// Generated by scripts/atlas-contract-fingerprint.mjs.\nexport const ATLAS_CONTRACT_SHA256 =\n  '${digest}' as const;\n`;
  if (mode === '--write') await writeFile(outputPath, expected);
  else if ((await readFile(outputPath, 'utf8')) !== expected)
    throw new TypeError('atlas_contract_fingerprint_stale');
  process.stdout.write(`${digest}\n`);
}
